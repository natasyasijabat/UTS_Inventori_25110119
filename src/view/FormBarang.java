    private void tampilData() {
        tableModel.setRowCount(0);
        for (Barang b : dao.getAll()) {
            tableModel.addRow(new Object[]{
                b.getKodeBarang(), b.getNamaBarang(), b.getKategori(), b.getStok()
            });
        }
    }

