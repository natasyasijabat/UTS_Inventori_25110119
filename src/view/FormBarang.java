    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        String kode = txtKode.getText().trim();
        String nama = txtNama.getText().trim();
        String kategori = cmbKategori.getSelectedItem().toString();
        int stok;

        if (kode.isEmpty() || nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pilih data dan isi nama terlebih dahulu!");
            return;
        }
        try {
            stok = Integer.parseInt(txtStok.getText().trim());
            if (stok < 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Stok harus berupa angka >= 0!");
            return;
        }

        if (dao.ubah(new Barang(kode, nama, kategori, stok))) {
            JOptionPane.showMessageDialog(this, "Data berhasil diubah.");
            tampilData();
            bersihkan();
        } else {
            JOptionPane.showMessageDialog(this, "Data gagal diubah.");
        }    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        String kode = txtKode.getText().trim();
        if (kode.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pilih data yang akan dihapus!");
            return;
        }
        int konfirmasi = JOptionPane.showConfirmDialog(this,
                "Yakin ingin menghapus barang " + kode + "?",
                "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);
        if (konfirmasi == JOptionPane.YES_OPTION) {
            if (dao.hapus(kode)) {
                JOptionPane.showMessageDialog(this, "Data berhasil dihapus.");
                tampilData();
                bersihkan();
            } else {
                JOptionPane.showMessageDialog(this, "Data gagal dihapus.");
            }
        }    }//GEN-LAST:event_btnHapusActionPerformed

